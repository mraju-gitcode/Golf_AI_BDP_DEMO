"""Test scenario metadata DB.

One SQLite table holds every test scenario with its metadata: source, category,
test type, expected outcome, open items, the design-canvas evaluation questions it
covers (E1 to E4), and the result of its most recent evaluation run.

Two sets:
- validated: Chris Schultz's 39 sample test cases (BDP_Rainbird_GolfPM_Sample_Test_Cases.xlsx,
  24 Nov 2026) plus 5 BDP red-team cases. This is the set every release is gated on.
- synthetic: story-based emails generated by golfpm.synthetic, for volume testing.

Seeded from data/test_cases.json and data/synthetic_cases.json on first use and on
every seed() call; results are kept across re-seeds.
"""
from __future__ import annotations

import json
import sqlite3
import threading
import time

from .config import DATA, RUNTIME, get_config

_lock = threading.RLock()
_conn: sqlite3.Connection | None = None

SETS = {"validated": "test_cases.json", "synthetic": "synthetic_cases.json"}
FILE_TO_SET = {v: k for k, v in SETS.items()}
SOURCE = {
    "TC": "Chris Schultz, GolfPM sample test cases (24 Nov 2026)",
    "RT": "BDP red-team set",
    "SY": "BDP synthetic generator (story-based)",
}
COLUMNS = ["id", "test_set", "source", "category", "category_name", "test_type", "scenario", "sender", "subject",
           "body", "cc", "attachments", "thread_of", "expected_category", "expected_action", "open_items",
           "evaluation_questions", "validated", "last_passed", "last_category", "last_action", "last_reason",
           "last_method", "last_run_at"]
SCHEMA = f"""
CREATE TABLE IF NOT EXISTS test_scenarios (
  id TEXT PRIMARY KEY, test_set TEXT, source TEXT, category INTEGER, category_name TEXT, test_type TEXT,
  scenario TEXT, sender TEXT, subject TEXT, body TEXT, cc TEXT, attachments TEXT, thread_of TEXT,
  expected_category INTEGER, expected_action TEXT, open_items TEXT, evaluation_questions TEXT,
  validated INTEGER, last_passed INTEGER, last_category INTEGER, last_action TEXT, last_reason TEXT,
  last_method TEXT, last_run_at REAL
);
"""


def _db() -> sqlite3.Connection:
    global _conn
    if _conn is None:
        RUNTIME.mkdir(parents=True, exist_ok=True)
        _conn = sqlite3.connect(RUNTIME / "golfpm_metadata.db", check_same_thread=False)
        _conn.row_factory = sqlite3.Row
        _conn.executescript(SCHEMA)
    return _conn


def eval_questions(cat, action) -> list[str]:
    """Design-canvas evaluation questions a scenario exercises."""
    qs = ["E1"]  # E1 categorize: every scenario
    if cat in (1, 2, 3) and action in ("reply", "ask", "approval", "escalate"):
        qs.append("E2")  # E2 act on assigned categories
    if cat and cat >= 4 or action in ("route", "file"):
        qs.append("E3")  # E3 route categories it does not own
    if action not in ("ignore",):
        qs.append("E4")  # E4 respond correctly
    return qs


def seed() -> int:
    """Upsert scenarios from the JSON sources, keeping each scenario's last result."""
    cfg = get_config()["categories"]
    rows = 0
    with _lock:
        c = _db()
        for test_set, fname in SETS.items():
            path = DATA / fname
            if not path.exists():
                continue
            cases = json.loads(path.read_text())["cases"]
            ids = [tc["id"] for tc in cases]
            c.execute(f"DELETE FROM test_scenarios WHERE test_set=? AND id NOT IN ({','.join('?' * len(ids))})",
                      [test_set, *ids])
            for tc in cases:
                cat = tc["expected"]["category"]
                action = tc["expected"]["action"]
                c.execute(
                    """INSERT INTO test_scenarios (id, test_set, source, category, category_name, test_type, scenario,
                         sender, subject, body, cc, attachments, thread_of, expected_category, expected_action,
                         open_items, evaluation_questions, validated)
                       VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)
                       ON CONFLICT(id) DO UPDATE SET test_set=excluded.test_set, source=excluded.source,
                         category=excluded.category, category_name=excluded.category_name, test_type=excluded.test_type,
                         scenario=excluded.scenario, sender=excluded.sender, subject=excluded.subject, body=excluded.body,
                         cc=excluded.cc, attachments=excluded.attachments, thread_of=excluded.thread_of,
                         expected_category=excluded.expected_category, expected_action=excluded.expected_action,
                         open_items=excluded.open_items, evaluation_questions=excluded.evaluation_questions,
                         validated=excluded.validated""",
                    (tc["id"], test_set, SOURCE.get(tc["id"][:2], "BDP"), cat,
                     cfg[str(cat)]["name"] if cat else "None (ignored)", tc.get("type", ""), tc.get("scenario", ""),
                     tc["from"], tc["subject"], tc["body"], json.dumps(tc.get("cc", [])),
                     json.dumps(tc.get("attachments", [])), tc.get("thread_of") or tc.get("duplicate_of"),
                     cat, action, tc.get("open_items", ""), ",".join(eval_questions(cat, action)),
                     1 if test_set == "validated" else 0))
                rows += 1
        c.commit()
    return rows


def _ensure():
    with _lock:
        if _db().execute("SELECT COUNT(*) FROM test_scenarios").fetchone()[0] == 0:
            seed()


def _to_case(r: sqlite3.Row) -> dict:
    """Row -> the test-case dict shape the pipeline and evaluation use."""
    d = dict(r)
    case = {"id": d["id"], "type": d["test_type"], "scenario": d["scenario"], "from": d["sender"],
            "subject": d["subject"], "body": d["body"], "cc": json.loads(d["cc"] or "[]"),
            "attachments": json.loads(d["attachments"] or "[]"),
            "expected": {"category": d["expected_category"], "action": d["expected_action"]},
            "open_items": d["open_items"]}
    return case


def load_cases(test_set: str = "validated") -> list[dict]:
    """Cases for the evaluation, including thread/duplicate links and seed rounds from the source file."""
    _ensure()
    source = {tc["id"]: tc for tc in json.loads((DATA / SETS[test_set]).read_text())["cases"]}
    with _lock:
        rows = _db().execute("SELECT * FROM test_scenarios WHERE test_set=? ORDER BY rowid", (test_set,)).fetchall()
    cases = []
    for r in rows:
        case = _to_case(r)
        src = source.get(case["id"], {})
        for k in ("thread_of", "duplicate_of", "seed_rounds"):
            if k in src:
                case[k] = src[k]
        cases.append(case)
    return cases


def record_results(results: list[dict], method: str | None) -> None:
    now = time.time()
    with _lock:
        c = _db()
        for r in results:
            c.execute("""UPDATE test_scenarios SET last_passed=?, last_category=?, last_action=?, last_reason=?,
                         last_method=?, last_run_at=? WHERE id=?""",
                      (int(r["passed"]), r["predicted_category"], r["predicted_action"], r["reason"], method, now, r["id"]))
        c.commit()


def list_scenarios(test_set: str = "validated") -> dict:
    _ensure()
    with _lock:
        rows = [dict(r) for r in _db().execute(
            "SELECT * FROM test_scenarios WHERE test_set=? ORDER BY rowid", (test_set,)).fetchall()]
    cfg = get_config()["categories"]
    by_cat = {k: {"name": v["short"], "count": 0, "passed": 0, "run": 0, "types": {}} for k, v in cfg.items()}
    by_cat["none"] = {"name": "Ignored (auto-reply, duplicate)", "count": 0, "passed": 0, "run": 0, "types": {}}
    by_type: dict[str, int] = {}
    questions: dict[str, int] = {"E1": 0, "E2": 0, "E3": 0, "E4": 0}
    for r in rows:
        r["cc"] = json.loads(r["cc"] or "[]")
        r["attachments"] = json.loads(r["attachments"] or "[]")
        b = by_cat[str(r["category"]) if r["category"] else "none"]
        b["count"] += 1
        b["types"][r["test_type"]] = b["types"].get(r["test_type"], 0) + 1
        if r["last_run_at"]:
            b["run"] += 1
            b["passed"] += r["last_passed"] or 0
        by_type[r["test_type"]] = by_type.get(r["test_type"], 0) + 1
        for q in (r["evaluation_questions"] or "").split(","):
            if q in questions:
                questions[q] += 1
    covered = sum(1 for k, v in by_cat.items() if k != "none" and v["count"])
    last = max((r["last_run_at"] or 0 for r in rows), default=0) or None
    return {"test_set": test_set, "scenarios": rows,
            "stats": {"total": len(rows), "categories_covered": covered, "categories_total": len(cfg),
                      "by_category": by_cat, "by_type": by_type, "evaluation_questions": questions,
                      "passed": sum(1 for r in rows if r["last_passed"]), "last_run_at": last,
                      "sources": sorted({r["source"] for r in rows}, key=lambda x: (not x.startswith("Chris"), x))}}
